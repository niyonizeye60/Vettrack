/**
 * One-off generator: reads GADM level-3 (sector) boundaries for Rwanda and
 * writes lib/rwanda-coordinates.ts. Kept in scripts/ so the coordinates file
 * can be regenerated instead of hand-edited.
 *
 * Run: node scripts/generate-rwanda-coordinates.mjs
 *
 * Source data: scripts/data/gadm41_RWA_3.json (GADM 4.1, level 3).
 * Re-download: https://geodata.ucdavis.edu/gadm/gadm4.1/json/gadm41_RWA_3.json.zip
 */
import { readFileSync, writeFileSync } from "fs"

const geo = JSON.parse(readFileSync("scripts/data/gadm41_RWA_3.json", "utf8"))

/** Flatten any GeoJSON geometry to [lng, lat] pairs (WGS84). */
function* coordsOf(geometry) {
  if (geometry.type === "GeometryCollection") {
    for (const g of geometry.geometries) yield* coordsOf(g)
    return
  }
  const rings =
    geometry.type === "Point" ? [[geometry.coordinates]] :
    geometry.type === "MultiPoint" || geometry.type === "LineString" ? [geometry.coordinates] :
    geometry.type === "MultiLineString" || geometry.type === "Polygon" ? geometry.coordinates :
    geometry.type === "MultiPolygon" ? geometry.coordinates.flat() : []
  for (const ring of rings) for (const [lng, lat] of ring) yield [lng, lat]
}

/**
 * Vertex-average centroid. Boundary rings put more vertices on complicated
 * borders, which pulls the average slightly toward the outline - good enough
 * for distance sorting, and fully deterministic.
 */
function centroid(geometry) {
  let sumLat = 0, sumLng = 0, n = 0
  for (const [lng, lat] of coordsOf(geometry)) {
    sumLng += lng
    sumLat += lat
    n++
  }
  return { lat: sumLat / n, lng: sumLng / n }
}

const byDistrict = {}
for (const f of geo.features) {
  const district = f.properties.NAME_2
  const sector = f.properties.NAME_3
  // GADM models Lake Kivu as a "sector" - not a real administrative sector.
  if (sector === "LacKivu") continue
  const { lat, lng } = centroid(f.geometry)
  ;(byDistrict[district] ||= {})[sector] = { lat: +lat.toFixed(4), lng: +lng.toFixed(4) }
}

const districts = Object.keys(byDistrict).sort()
let sectorCount = 0
for (const d of districts) sectorCount += Object.keys(byDistrict[d]).length

const lines = []
lines.push(`// AUTO-GENERATED by scripts/generate-rwanda-coordinates.mjs - do not hand-edit.`)
lines.push(`// Source: GADM 4.1 admin level 3 (sector) boundaries for Rwanda (scripts/data/gadm41_RWA_3.json), vertex-average centroids.`)
lines.push(`// ${districts.length} districts, ${sectorCount} sector entries.`)
lines.push(``)
lines.push(`export const sectorCoordinates: Record<string, Record<string, { lat: number; lng: number }>> = {`)
for (const d of districts) {
  lines.push(`  "${d}": {`)
  for (const s of Object.keys(byDistrict[d]).sort()) {
    const { lat, lng } = byDistrict[d][s]
    lines.push(`    "${s}": { lat: ${lat}, lng: ${lng} },`)
  }
  lines.push(`  },`)
}
lines.push(`}`)
lines.push(``)
lines.push(`export const districtCoordinates: Record<string, { lat: number; lng: number }> = {`)
for (const d of districts) {
  // District point = average of its sector points.
  const secs = Object.values(byDistrict[d])
  const lat = (secs.reduce((s, p) => s + p.lat, 0) / secs.length).toFixed(4)
  const lng = (secs.reduce((s, p) => s + p.lng, 0) / secs.length).toFixed(4)
  lines.push(`  "${d}": { lat: ${lat}, lng: ${lng} },`)
}
lines.push(`}`)
lines.push(``)

writeFileSync("lib/rwanda-coordinates.ts", lines.join("\n"))
console.log(`Wrote lib/rwanda-coordinates.ts: ${districts.length} districts, ${sectorCount} sectors`)
