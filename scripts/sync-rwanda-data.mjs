/**
 * One-off sync: rewrites lib/rwanda-data.ts so its district/sector lists match
 * the GADM names used by lib/rwanda-coordinates.ts exactly.
 *
 * Run: node scripts/sync-rwanda-data.mjs
 */
import { readFileSync, writeFileSync } from "fs"

// --- parse lib/rwanda-coordinates.ts (fixed generated layout) ---------------
const coordsSrc = readFileSync("lib/rwanda-coordinates.ts", "utf8")
const gadm = {}
for (const m of coordsSrc.matchAll(/"([^"]+)": \{\n((?:    "[^"]+": \{[^}]*\},?\n)+)  \}/g)) {
  gadm[m[1]] = {}
  for (const s of m[2].matchAll(/"([^"]+)": \{ lat: ([\d.-]+), lng: ([\d.-]+) \}/g)) {
    gadm[m[1]][s[1]] = true
  }
}

const districts = Object.keys(gadm).sort()
if (districts.length < 30) {
  console.error(`Expected 30 districts in rwanda-coordinates.ts, got ${districts.length} - aborting`)
  process.exit(1)
}

const lines = []
lines.push(`// GADM 4.1 official administrative names for Rwanda: 30 districts, ${districts.reduce((n, d) => n + Object.keys(gadm[d]).length, 0)} sectors.`)
lines.push(`// Generated by scripts/sync-rwanda-data.mjs - matches lib/rwanda-coordinates.ts 1:1.`)
lines.push(``)
lines.push(`export const rwandaData: Record<string, string[]> = {`)
for (const d of districts) {
  const sectors = Object.keys(gadm[d]).sort()
  const items = sectors.map((s) => `"${s}"`).join(", ")
  lines.push(`  "${d}": [${items}],`)
}
lines.push(`}`)
lines.push(``)

writeFileSync("lib/rwanda-data.ts", lines.join("\n"))

let sectorCount = 0
for (const d of districts) sectorCount += Object.keys(gadm[d]).length
console.log(`Wrote lib/rwanda-data.ts: ${districts.length} districts, ${sectorCount} sectors`)
